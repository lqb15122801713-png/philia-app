const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const q = (t) => [...document.querySelectorAll('button')].find(b => b.innerText.trim().includes(t));
window.scrollTo(0, document.body.scrollHeight);
await sleep(500);
const btn = q('改期');
if (!btn) return 'NO-RESCHEDULE-BUTTON';
btn.click();
await sleep(2000);
const day = q('9月9日');
if (!day) return 'NO-DAY-TAB';
day.click();
await sleep(800);
const slot = [...document.querySelectorAll('button')].find(b => b.innerText.trim() === '14:00' && !b.disabled);
if (!slot) return 'NO-SLOT-1400';
slot.click();
await sleep(500);
const ok = q('确认改期');
if (!ok || ok.disabled) return 'CONFIRM-DISABLED';
ok.click();
await sleep(2000);
return document.body.innerText.includes('改期已提交') ? 'TOAST-OK' : 'toast-missing: ' + document.body.innerText.slice(0, 300);
